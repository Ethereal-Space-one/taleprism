"""Render portable prompts and schemas from the exact rules used by the workbench."""

import argparse
import json
from pathlib import Path

from storygal.production import Plan, plan_task_schema
from storygal.prompts import library, metadata, render, rules_text

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    lib = library()
    result = {}
    for stage in lib["stages"]:
        variables = {name: "{{" + name + "}}" for name in stage["inputs"]}
        result["prompts/" + stage["id"] + ".md"] = "\n".join(
            [
                "# " + stage["title"],
                "",
                "Taleprism " + lib["version"],
                "",
                stage["purpose"],
                "",
                "## 输入 / Inputs",
                "",
                *["- `" + k + "`: " + v for k, v in stage["inputs"].items()],
                "",
                "## 可复制模板 / Copyable prompt",
                "",
                "Replace the `{{variables}}` below, and attach actual image files when requested. 文件名不能代替上传图片。",
                "",
                "```text",
                render(stage["id"], variables),
                "```",
                "",
                "## 完整填写示例 / Filled Last Light example",
                "",
                "Use alongside [the tutorial](../examples/last-light/README.md). Example text contains artistic choices; keep the original novel unchanged.",
                "",
                "```text",
                render(stage["id"], stage["example_inputs"]),
                "```",
                "",
                "## 预期结果 / Expected result",
                "",
                "This is a worked example, not a new model run or approval of your output.",
                "",
                "```json",
                json.dumps(stage["example_output"], ensure_ascii=False, indent=2),
                "```",
                "",
                "## 检查与恢复 / Check and recover",
                "",
                *["- " + c for c in stage["checks"]],
                "",
                stage["recovery"],
                "",
                "Generated by `tools/export_prompt_kit.py`. Edit the shared `backend/src/storygal/prompt_library.json`, then regenerate. Do not edit this file independently.",
                "",
            ]
        )
    result["prompts/RULES.md"] = (
        "# Taleprism shared rules / 共用规则\n\n" + rules_text() + "\n"
    )
    result["prompts/manifest.json"] = (
        json.dumps(
            {**metadata(), "templates": [s["id"] for s in lib["stages"]]}, indent=2
        )
        + "\n"
    )
    for name, schema in [
        ("plan", Plan.model_json_schema()),
        ("plan-task", plan_task_schema()),
    ]:
        result["schemas/" + name + ".schema.json"] = (
            json.dumps(
                {"$schema": "https://json-schema.org/draft/2020-12/schema", **schema},
                ensure_ascii=False,
                indent=2,
            )
            + "\n"
        )
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, value in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != value:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value, encoding="utf-8")
    if stale:
        raise SystemExit("Regenerate prompt kit: " + ", ".join(stale))
    print("Prompt templates and schemas are current.")


if __name__ == "__main__":
    main()
