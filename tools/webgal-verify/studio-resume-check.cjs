// Exercise interrupted creator sessions on a disposable local workbench only.
const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const base = new URL(process.argv[2])
assert.equal(base.hostname, '127.0.0.1', 'pass a disposable loopback workbench URL')
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAACAAAAASCAIAAAC1qksFAAAAIUlEQVR4nGNM6algoCVgoqnpoxaMWjBqwagFoxaMWgAFABaYAYyXLNXXAAAAAElFTkSuQmCC', 'base64')
const original = Buffer.from('\ufeff雨落在门外的青石地上。\r\n第二段才看见窗口的一盏灯。\r\n')

;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/chromium', headless: true })
  try {
    const context = await browser.newContext({baseURL:base.href})
    const oldTab = await context.newPage()
    const resp = await context.request.post('/api/projects', {multipart: { file: {name:'旧作.txt', mimeType:'text/plain', buffer:Buffer.from('不覆盖旧作品和未保存输入。')},rights_status:'local_test'}})
    assert(resp.ok()); const old = (await resp.json()).id
    await oldTab.goto('/?studio=' + old)
    await oldTab.getByRole('alert').filter({hasText:'未作任何修改'}).waitFor()
    await oldTab.goto('/?project=' + old)
    await oldTab.getByRole('button',{name:'独立阅读器',exact:true}).click()
    await oldTab.getByText('编辑封面、场景与人物',{exact:true}).click()
    const previousDraft = oldTab.getByLabel('章节名称',{exact:true})
    await previousDraft.fill('未保存的旧项目标题')
    const [studio] = await Promise.all([oldTab.waitForEvent('popup'), oldTab.getByRole('link',{name:'＋ 用自己的图文开始'}).click()])
    const errors=[], external=[]
    studio.on('pageerror', e => errors.push(e.message))
    studio.on('request', r => {if (new URL(r.url()).origin !== base.origin) external.push(r.url())})
    await studio.getByLabel('作品标题').fill('临时标题')
    await studio.getByLabel('粘贴自己的原文').fill('切换输入方式也保留这段尚未提交的文字。')
    const mode = studio.getByLabel('原文输入方式')
    await mode.selectOption('file'); await mode.selectOption('paste')
    assert.equal(await studio.getByLabel('作品标题').inputValue(), '临时标题')
    await mode.selectOption('file')
    await studio.getByLabel('原文 TXT 文件').setInputFiles({name:'测试手稿.TXT', mimeType:'text/plain', buffer:original})
    await studio.getByLabel('原文权利状态').selectOption('owned')
    let creates=0
    studio.on('request', r => {if (r.method()==='POST' && new URL(r.url()).pathname === '/api/projects') creates++})
    await studio.getByRole('checkbox',{name:'插图',exact:true}).check()
    await studio.getByRole('button',{name:'新建项目，开始制作 →'}).evaluate(b => {b.click();b.click()})
    await studio.getByRole('heading',{name:'把插图放进原文'}).waitFor()
    assert.equal(creates, 1); assert.equal(await previousDraft.inputValue(), '未保存的旧项目标题')
    const id = new URL(studio.url()).searchParams.get('studio'), prefix = '/api/projects/' + id
    assert.notEqual(id, 'new'); assert.notEqual(id, old)
    assert.deepEqual(await (await context.request.get(prefix + '/source')).body(),original)
    const read = async()=> (await context.request.get(prefix+'/reader')).json()
    const write = (revision,config)=>context.request.patch(prefix+'/reader',{data:{revision,...config}})
    await studio.getByLabel('插图文件').setInputFiles({name:'broken.png',mimeType:'image/png',buffer:Buffer.from('not an image')})
    await studio.getByLabel('图片来源与许可').fill('自行绘制的验证图片')
    await studio.getByRole('button',{name:'上传为候选图'}).click()
    await studio.getByRole('alert').filter({hasText:'已保存的项目和素材仍在'}).waitFor()
    await studio.getByLabel('插图文件').setInputFiles({name:'fixture.png',mimeType:'image/png',buffer:png})
    await studio.getByRole('button',{name:'上传为候选图'}).click()
    await studio.getByRole('button',{name:'接受这张底图'}).waitFor()
    await studio.reload()
    assert.equal((await read()).assets[0].status,'pending')
    const place=studio.getByRole('button',{name:'放置静图，进入动效导演 →'})
    await studio.getByLabel('放在此段之后').selectOption({index:2})
    assert.equal(await place.isEnabled(),false); await studio.getByRole('button',{name:'接受这张底图'}).click()
    await studio.getByText(/✓ 底图已接受/).waitFor()
    await studio.getByLabel('插图名称').fill('核准的静图')
    let state = await read()
    assert((await write(state.revision,{...state.config, subtitle:'另一个标签页刚保存的副标题'})).ok())
    await place.click()
    await studio.getByRole('alert').filter({hasText:'配置已更新'}).waitFor()
    assert.equal(await studio.getByLabel('插图名称').inputValue(),'核准的静图')
    await place.click()
    const director = studio.locator('.motion-director[open]')
    await director.waitFor()
    state=await read(); assert.equal(state.config.subtitle,'另一个标签页刚保存的副标题')
    assert.equal(state.config.illustrations[0].after_byte,state.paragraphs[1].byte_end)
    assert.equal(state.config.illustrations[0].motion,null)
    await studio.reload(); await director.waitFor()
    // A stale editor must neither overwrite a newer change nor lose the local one.
    await director.getByRole('button',{name:'只用静图'}).click()
    const save=studio.getByRole('button',{name:'保存章节编排',exact:true})
    assert((await write(state.revision,{...state.config,subtitle:'这个版本不能被覆盖'})).ok())
    await save.click()
    await studio.getByRole('button',{name:'重新载入此项目'}).waitFor()
    studio.once('dialog',d=>d.dismiss())
    await studio.getByRole('button',{name:'重新载入此项目'}).click()
    assert.equal(await save.isEnabled(),false)
    assert.equal((await read()).config.subtitle,'这个版本不能被覆盖')
    const before = studio.url()
    const leaveWarning = studio.waitForEvent('dialog').then(async d => {const kind = d.type(); await d.dismiss(); return kind})
    await studio.getByRole('link',{name:'返回完整工作台'}).click({noWaitAfter:true})
    assert.equal(await leaveWarning, 'beforeunload')
    assert.equal(studio.url(),before)
    assert.equal(await previousDraft.inputValue(),'未保存的旧项目标题')
    // The actual ZIP importer opens the ordinary workbench; its optional return
    // link must resolve to this *new* restored project, not our current tab.
    const packageResponse = await context.request.get(prefix + '/bundle')
    assert(packageResponse.ok())
    const restoredTab = await context.newPage()
    await restoredTab.goto('/')
    await restoredTab.getByText('手动导入与原文练习',{exact:true}).click()
    await restoredTab.getByLabel('导入可编辑工程',{exact:true}).setInputFiles({name:'restored.zip', mimeType:'application/zip', buffer:await packageResponse.body()})
    const resume = restoredTab.getByRole('link',{name:'继续单幅图文制作 ↗'})
    await resume.waitFor()
    const restoredId = new URL(await resume.getAttribute('href'), base).searchParams.get('studio')
    assert.notEqual(restoredId,id); assert.notEqual(restoredId,old)
    const [restoredStudio] = await Promise.all([restoredTab.waitForEvent('popup'), resume.click()])
    await restoredStudio.locator('.motion-director[open]').waitFor()
    assert.equal(await restoredStudio.locator('.studio-motion h2').textContent(), '核准的静图')
    assert.deepEqual(await (await context.request.get('/api/projects/' + restoredId + '/source')).body(), original)
    assert.deepEqual(external,[]); assert.deepEqual(errors,[])
    console.log(JSON.stringify({passed:true, oldDraftPreserved:true,txtBytesPreserved:true, duplicateCreatesPrevented:true, failedImageRetried:true, reloadResumed:true, assetReviewRequired:true, stalePlacementProtected:true, staleEditorProtected:true, dirtyLeavePrevented:true,restoredStudioLink:true,externalRequests:0}))
  } finally { await browser.close() }
})().catch(e=>{console.error(e);process.exitCode=1})
