const assert = require('node:assert/strict')
const fs = require('node:fs')
const {chromium} = require('playwright')
const base = process.argv[2] || 'http://127.0.0.1:8136'
const output = process.env.TALEPRISM_GUIDED_QA_OUTPUT || '/tmp/taleprism-guided-qa-artifacts'
fs.mkdirSync(output, {recursive:true})
;(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || '/usr/bin/chromium',headless:true})
  const context=await browser.newContext({viewport:{width:1440,height:1000}})
  const page=await context.newPage(), errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  const report={passed:false}
  try {
    await page.goto(base)
    await page.getByRole('button',{name:'修一幅《末班灯》',exact:true}).waitFor()
    assert.equal(await page.locator('.exchange-manual').getAttribute('open'),null)
    assert.equal(await page.evaluate(()=>getComputedStyle(document.querySelector('.creator-workbench')).backgroundColor),'rgb(255, 255, 255)')
    await page.screenshot({path:output+'/landing-desktop.png',fullPage:true})
    await page.setViewportSize({width:375,height:900})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    await page.screenshot({path:output+'/landing-mobile.png',fullPage:true})
    await page.setViewportSize({width:1440,height:1000})
    let starts=0
    page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/api/samples/last-light/guided'))starts++})
    await page.getByRole('button',{name:'修一幅《末班灯》',exact:true}).evaluate(el=>{el.click();el.click()})
    await page.locator('.guided-steps').waitFor()
    await page.locator('#shot-negotiation[open]').waitFor()
    assert.equal(starts,1)
    const pid=await page.evaluate(()=>localStorage.getItem('storygal-project'))
    const before=await (await page.request.get(base+'/api/projects/'+pid+'/production')).json()
    const source=await (await page.request.get(base+'/api/projects/'+pid+'/source')).body()
    assert.equal(before.plan.shots.length,3)
    await page.screenshot({path:output+'/opened-guided-desktop.png',fullPage:true})
    const field=page.locator('#shot-negotiation').getByLabel('具体发生在哪一刻',{exact:true})
    const original=await field.inputValue()
    await field.fill(original+'；练习：停顿后再抬眼。')
    await page.getByRole('button',{name:'保存方案',exact:true}).click()
    await page.getByText('方案已保存。',{exact:true}).waitFor()
    await page.locator('.guided-steps').getByText(/已保存方案中有 [1-9] 幅需要复核/).waitFor()
    assert.deepEqual(await (await page.request.get(base+'/api/projects/'+pid+'/source')).body(),source)
    const after=await (await page.request.get(base+'/api/projects/'+pid+'/production')).json()
    assert.equal(after.plan.shots[0].continuity_check.status,'passed')
    assert.equal(after.plan.shots[1].continuity_check.status,'stale')
    assert.equal(after.plan.shots[2].continuity_check.status,'stale')
    await page.locator('.guided-steps').getByRole('button',{name:'查看待复核镜头 →',exact:true}).click()
    await page.locator('#shot-negotiation[open]').waitFor()
    await page.reload()
    await page.locator('.guided-steps').waitFor()
    assert.equal(await page.evaluate(()=>localStorage.getItem('storygal-project')),pid)
    await page.locator('.guided-steps').getByRole('button',{name:'打开阅读器与预览 →',exact:true}).click()
    await page.getByRole('heading',{name:'独立阅读器',exact:true}).waitFor()
    const popupPromise=page.waitForEvent('popup')
    await page.locator('.guided-steps').getByRole('link',{name:'新窗口查看当前阅读版 ↗',exact:true}).click()
    const reader=await popupPromise
    await reader.getByRole('button',{name:/^开始阅读/}).click()
    await reader.locator('.reader-plate').first().waitFor()
    assert.equal(await reader.locator('.reader-plate').count(),3)
    await reader.close()
    await page.setViewportSize({width:375,height:900})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    await page.screenshot({path:output+'/guided-mobile.png',fullPage:true})
    await page.setViewportSize({width:1440,height:1000})
    await page.getByText('手动导入与原文练习',{exact:true}).click()
    await page.getByLabel('本地内容包').selectOption('last-light')
    assert.equal(await page.getByRole('button',{name:'下载后导入工程',exact:true}).isDisabled(),true)
    await page.getByRole('link',{name:'下载示例工程 ↗',exact:true}).waitFor()
    await page.getByRole('button',{name:'仅从《末班灯》原文开始',exact:true}).click()
    await page.waitForFunction(previous=>localStorage.getItem('storygal-project')!==previous,pid)
    const rawPid=await page.evaluate(()=>localStorage.getItem('storygal-project'))
    const rawPlan=await (await page.request.get(base+'/api/projects/'+rawPid+'/production')).json()
    assert.equal(rawPlan.plan.shots.length,0)
    assert.equal(await page.locator('.guided-steps').count(),0)
    // Starting a second copy must not steal a newer project selection while it completes.
    let release
    const gate=new Promise(resolve=>release=resolve)
    await page.route('**/api/samples/last-light/guided',async route=>{
      if(route.request().method()!=='POST')return route.continue()
      await gate
      return route.continue()
    })
    await page.getByRole('button',{name:'《末班灯》引导练习',exact:true}).click()
    await page.locator('.project').filter({hasText:'末班灯'}).first().click()
    const chosen=await page.evaluate(()=>localStorage.getItem('storygal-project'))
    release()
    await page.getByText('完整样例已另存为新项目。你切换后的当前项目未改动。',{exact:true}).waitFor()
    assert.equal(await page.evaluate(()=>localStorage.getItem('storygal-project')),chosen)
    await page.getByRole('button',{name:'打开刚准备的《末班灯》副本 →',exact:true}).click()
    await page.locator('.guided-steps').waitFor()
    await page.locator('.guided-steps').getByRole('button',{name:'收起引导',exact:true}).click()
    assert.equal(await page.locator('.guided-steps').count(),0)
    await page.reload()
    assert.equal(await page.locator('.guided-steps').count(),0)
    assert.deepEqual(errors,[])
    Object.assign(report,{passed:true,one_click_complete_sample:true,repeat_click_guard:true,edit_stales_two_checks:true,source_unchanged:true,reload_resumes:true,manual_and_raw_separate:true,preview_three_plates:true,newer_navigation_preserved:true,desktop_mobile:true,errors})
  }catch(e){report.error=String(e.stack||e);await page.screenshot({path:output+'/failure.png',fullPage:true}).catch(()=>{});throw e}
  finally{fs.writeFileSync(output+'/report.json',JSON.stringify(report,null,2));await browser.close()}
  console.log(JSON.stringify(report,null,2))
})().catch(e=>{console.error(e);process.exit(1)})
